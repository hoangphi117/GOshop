// Builds docs/SERVICES.md from the things that actually exist: compose port
// mappings, service DB names, proto contracts, service migrations. Nothing is
// typed by hand, so it cannot drift from the code. Re-run after adding or
// moving a service.
const fs = require("node:fs");
const path = require("node:path");

const root = process.cwd();
const svcRoot = path.join(root, "backend/gomod/services");

// --- compose: prod is the source of truth for published ports and DB names.
const compose = fs.readFileSync(path.join(root, "docker-compose.prod.yml"), "utf8");

function serviceBlock(name) {
  const re = new RegExp(`^  ${name}:\\s*$`, "m");
  const m = compose.match(re);
  if (!m) return "";
  const rest = compose.slice(m.index + m[0].length);
  const end = rest.search(/^  [a-z0-9_-]+:\s*$/m);
  return end === -1 ? rest : rest.slice(0, end);
}

function envOf(block, key) {
  // compose accepts both list form (`- KEY=value`) and map form (`KEY: "value"`)
  const list = block.match(new RegExp(`^\\s+-\\s*${key}=([^"'\\n]+)`, "m"));
  if (list) return list[1].trim().replace(/\$\{[^}]*\}/g, "");
  const map = block.match(new RegExp(`^\\s+${key}:[ \\t]*["']?([^"'\\n]+)["']?[ \\t]*$`, "m"));
  return map ? map[1].trim().replace(/\$\{[^}]*\}/g, "") : "";
}

// --- proto contracts: shared/proto/<name>/v1/<name>.proto
const protoRoot = path.join(root, "backend/gomod/shared/proto");
const protos = fs.existsSync(protoRoot)
  ? fs.readdirSync(protoRoot, { withFileTypes: true }).filter((d) => d.isDirectory()).map((d) => d.name)
  : [];

// --- routing keys are declared once in contracts/events; the broker carries all of them.
const eventsSrc = fs.readFileSync(path.join(root, "backend/gomod/contracts/events/events.go"), "utf8");
const routingKeys = {};
for (const m of eventsSrc.matchAll(/RoutingKey\w+\s*=\s*"([^"]+)"/g)) routingKeys[m[1]] = true;

const services = fs
  .readdirSync(svcRoot, { withFileTypes: true })
  .filter((d) => d.isDirectory() && !d.name.startsWith("."))
  .map((d) => d.name)
  .sort();

const rows = [];
for (const svc of services) {
  const dir = path.join(svcRoot, svc);
  const block = serviceBlock(`${svc}-service`) || serviceBlock(svc);
  const upper = svc.toUpperCase();
  const httpPort = envOf(block, `${upper}_SERVER_PORT`) || envOf(block, "SERVER_PORT") || envOf(block, "PORT");
  const grpcPort = envOf(block, `${upper}_GRPC_PORT`) || envOf(block, "GRPC_PORT");
  const db = envOf(block, `${upper}_DB_NAME`) || envOf(block, "DB_NAME");

  const migrationsDir = path.join(dir, "internal/migrations");
  const migrations = fs.existsSync(migrationsDir)
    ? fs.readdirSync(migrationsDir).filter((f) => f.endsWith(".up.sql")).length
    : 0;

  rows.push({ svc, httpPort, grpcPort, db, proto: protos.includes(svc), migrations });
}

const cell = (v) => (v ? `\`${v}\`` : "—");
const out = [];
out.push("# Services");
out.push("");
out.push(
  "One module, one database schema and one migration set per domain. Generated by",
  "`node scripts/gen-services-doc.cjs` from `docker-compose.prod.yml`, the service migrations and the",
  "proto contracts — re-run it after adding or moving a service instead of editing this file by hand.",
);
out.push("");
out.push("| Service | HTTP | gRPC | Database | Migrations | Contract |");
out.push("|---|---|---|---|---|---|");
for (const r of rows) {
  out.push(
    `| [\`${r.svc}\`](../backend/gomod/services/${r.svc}) | ${cell(r.httpPort)} | ${cell(r.grpcPort)} | ${cell(
      r.db,
    )} | ${r.migrations || "—"} | ${r.proto ? `\`shared/proto/${r.svc}/v1\`` : "—"} |`,
  );
}
out.push("");
out.push("## Notes");
out.push("");
out.push(
  "- Ports come from the prod compose environment. nginx is the only published entry point; the",
  "  per-service ports are reachable inside the compose network.",
);
out.push(
  "- **No database does not mean no state.** `assistant` keeps conversation sessions and the",
  "  per-user daily quota in Redis; `media` keeps uploaded bytes in object storage (R2/MinIO) and",
  "  is stateless itself. Both are deliberately single-store services: Postgres would add a",
  "  migration set and a backup obligation for data that ages out on its own. A dash in the",
  "  Database column is that decision, not an omission.",
);
out.push(
  "- **No gRPC does not mean no callers.** `banner`, `notification`, `review`, `analytics` and",
  "  `recommendations` are reached over HTTP through the gateway or fed by Kafka events; none of",
  "  them needs a synchronous typed call on the checkout path. `recommendations` still owns seven",
  "  migrations — a shelf lookup returns a composed JSON page, not a single entity worth a proto.",
);
out.push(
  "- **gRPC is a request-path tool, not a default.** It is used where a caller needs a typed,",
  "  deadline-bounded answer mid-transaction (checkout pricing, stock reservation, order→payment",
  "  reads). Adding a proto for a service only the edge talks to buys a second contract surface to",
  "  version for no caller.",
);
out.push(
  `- Event routing keys are declared once in [\`contracts/events/events.go\`](../backend/gomod/contracts/events/events.go) (${Object.keys(routingKeys).length} keys). Which service consumes which key is per-handler dispatch logic, so read the service's \`consumer/\` or \`worker/\` package rather than trusting a table.`,
);
out.push(
  "- Only `order` also carries a hand-written `README.md` (ownership, failure modes, runbook). The",
  "  table above is the index for the rest; add prose to a service README only when it owns",
  "  non-obvious behaviour worth a reviewer's time.",
);
out.push(
  "- Checkout end to end, compensation and the failure matrix: [`ARCHITECTURE.md`](ARCHITECTURE.md).",
);
out.push(
  "- Full request/response shapes: `/swagger/index.html` on the edge, or",
  "  `backend/gomod/shared/docs/swagger.json`.",
);
out.push("");

fs.mkdirSync(path.join(root, "docs"), { recursive: true });
fs.writeFileSync(path.join(root, "docs", "SERVICES.md"), out.join("\n"));
console.log(`docs/SERVICES.md written: ${rows.length} services`);
for (const r of rows) {
  console.log(`  ${r.svc} | http=${r.httpPort || "-"} grpc=${r.grpcPort || "-"} db=${r.db || "-"}`);
}
