CREATE INDEX IF NOT EXISTS idx_reviews_product_filter ON product_reviews(review_product_id, review_status, review_rating, review_has_media, review_created_at DESC);
CREATE INDEX IF NOT EXISTS idx_product_reviews_order_uuid ON product_reviews(review_order_uuid);
