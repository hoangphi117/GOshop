COMMENT ON COLUMN product_reviews.review_status IS '1: Visible, 2: Hidden, 3: Reported';

CREATE INDEX IF NOT EXISTS idx_reviews_product ON product_reviews(review_product_id, review_status, review_created_at DESC);
