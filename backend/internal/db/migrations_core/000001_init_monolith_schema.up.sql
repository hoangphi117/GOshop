CREATE TABLE IF NOT EXISTS product_reviews (
    review_id            INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    review_uuid          UUID DEFAULT gen_random_uuid() NOT NULL UNIQUE,
    review_user_id       INT NOT NULL,
    review_product_id    INT NOT NULL,
    review_order_id      INT DEFAULT NULL,
    review_order_uuid    UUID NOT NULL DEFAULT gen_random_uuid(),
    review_rating        SMALLINT NOT NULL CHECK (review_rating BETWEEN 1 AND 5),
    review_title         VARCHAR(200),
    review_comment       TEXT,
    review_images        TEXT[] DEFAULT '{}' NOT NULL,
    review_video_url     TEXT,
    review_has_media     BOOLEAN DEFAULT false NOT NULL,
    review_status        SMALLINT DEFAULT 1 NOT NULL CHECK (review_status IN (1, 2, 3)),
    review_edit_count    INT DEFAULT 0 NOT NULL,
    review_helpful_count INT DEFAULT 0 NOT NULL,
    review_user_name     VARCHAR(100) DEFAULT '' NOT NULL,
    review_user_email    VARCHAR(255) DEFAULT '' NOT NULL,
    review_user_avatar   VARCHAR(500) DEFAULT '' NOT NULL,
    review_reply         TEXT DEFAULT NULL,
