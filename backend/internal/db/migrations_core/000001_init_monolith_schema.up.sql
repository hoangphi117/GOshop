CREATE TABLE IF NOT EXISTS coupons (
    coupon_id              INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    coupon_uuid            UUID DEFAULT gen_random_uuid() NOT NULL UNIQUE,
    coupon_code            VARCHAR(50) NOT NULL UNIQUE,
    coupon_name            VARCHAR(100) NOT NULL,
    coupon_description     TEXT,
    coupon_type            INT DEFAULT 1 CHECK (coupon_type IN (1, 2)) NOT NULL,
    coupon_discount_value  NUMERIC(12,2) NOT NULL CHECK (coupon_discount_value > 0),
    coupon_min_order_value NUMERIC(12,2) DEFAULT 0.00 NOT NULL CHECK (coupon_min_order_value >= 0),
    coupon_max_discount    NUMERIC(12,2) DEFAULT NULL,
    coupon_usage_limit     INT DEFAULT NULL CHECK (coupon_usage_limit IS NULL OR coupon_usage_limit > 0),
    coupon_used_count      INT DEFAULT 0 NOT NULL,
    coupon_start_date      TIMESTAMPTZ NOT NULL,
    coupon_end_date        TIMESTAMPTZ NOT NULL,
    coupon_status          INT DEFAULT 1 CHECK (coupon_status IN (1, 2, 3)) NOT NULL,
    coupon_created_at      TIMESTAMPTZ DEFAULT now() NOT NULL,
    coupon_updated_at      TIMESTAMPTZ DEFAULT now() NOT NULL,
    CONSTRAINT chk_coupon_dates CHECK (coupon_end_date > coupon_start_date)
);

COMMENT ON COLUMN coupons.coupon_type IS '1: Percentage, 2: Fixed Amount';
COMMENT ON COLUMN coupons.coupon_status IS '1: Active, 2: Inactive, 3: Expired';

CREATE INDEX IF NOT EXISTS idx_coupons_code ON coupons(coupon_code);
CREATE INDEX IF NOT EXISTS idx_coupons_status ON coupons(coupon_status);
CREATE INDEX IF NOT EXISTS idx_coupons_dates ON coupons(coupon_start_date, coupon_end_date);

CREATE TABLE IF NOT EXISTS coupon_usages (
    coupon_usage_id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    coupon_usage_uuid        UUID DEFAULT gen_random_uuid() NOT NULL UNIQUE,
    coupon_usage_coupon_id   INT NOT NULL REFERENCES coupons(coupon_id) ON DELETE RESTRICT,
    coupon_usage_coupon_uuid UUID NOT NULL DEFAULT '00000000-0000-0000-0000-000000000000',
    coupon_usage_user_id     INT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    coupon_usage_user_uuid   UUID NOT NULL DEFAULT '00000000-0000-0000-0000-000000000000',
    coupon_usage_order_id    INT DEFAULT NULL,
    coupon_usage_order_uuid  UUID DEFAULT NULL,
    coupon_usage_used_at     TIMESTAMPTZ DEFAULT now() NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_coupon_usages_coupon ON coupon_usages(coupon_usage_coupon_id);
CREATE INDEX IF NOT EXISTS idx_coupon_usages_user ON coupon_usages(coupon_usage_user_id);
CREATE INDEX IF NOT EXISTS idx_coupon_usages_user_uuid ON coupon_usages(coupon_usage_user_uuid);
CREATE INDEX IF NOT EXISTS idx_coupon_usages_order_uuid ON coupon_usages(coupon_usage_order_uuid);
CREATE UNIQUE INDEX IF NOT EXISTS uq_coupon_usages_order_uuid ON coupon_usages (coupon_usage_order_uuid) WHERE coupon_usage_order_uuid IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS uq_coupon_usages_order_id ON coupon_usages (coupon_usage_order_id) WHERE coupon_usage_order_id IS NOT NULL;

CREATE OR REPLACE FUNCTION update_coupon_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.coupon_updated_at = now();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

