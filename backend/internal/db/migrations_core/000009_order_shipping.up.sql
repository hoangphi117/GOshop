-- ── 1. Bổ sung cột shipping vào bảng orders ──────────────────
ALTER TABLE orders
    ADD COLUMN order_shipping_provider  VARCHAR(20),   -- 'ghn', 'manual'
    ADD COLUMN order_shipping_code      VARCHAR(50),   -- Mã vận đơn từ GHN
    ADD COLUMN order_shipping_fee       NUMERIC(12,2) DEFAULT 0.00 NOT NULL,
    ADD COLUMN order_expected_delivery  TIMESTAMPTZ,   -- Ngày dự kiến giao
    ADD COLUMN order_delivered_at       TIMESTAMPTZ,
    ADD COLUMN order_returned_at        TIMESTAMPTZ;

-- ── 2. Bảng order_tracking_events (Timeline) ─────────────────
CREATE TABLE IF NOT EXISTS order_tracking_events (
    event_id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_order_id   INT NOT NULL REFERENCES orders(order_id) ON DELETE CASCADE,
    event_status     VARCHAR(50) NOT NULL,     -- 'pending', 'confirmed', 'picking', 'shipping', 'delivered', etc.
    event_note       TEXT,
    event_source     VARCHAR(20) DEFAULT 'system' NOT NULL, -- 'system', 'admin', 'ghn', 'user'
    event_created_at TIMESTAMPTZ DEFAULT now() NOT NULL
);

CREATE INDEX idx_tracking_order ON order_tracking_events(event_order_id, event_created_at DESC);

-- ── 3. Bảng order_returns (Yêu cầu trả hàng) ──────────────────
CREATE TABLE IF NOT EXISTS order_returns (
    return_id                INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    return_uuid              UUID DEFAULT gen_random_uuid() NOT NULL UNIQUE,
    return_order_id          INT NOT NULL REFERENCES orders(order_id) ON DELETE CASCADE,
    return_user_id           INT NOT NULL,
    return_reason            TEXT NOT NULL,
    return_images            TEXT[] DEFAULT '{}' NOT NULL,
    return_video_url         TEXT,
    return_status            SMALLINT DEFAULT 1 NOT NULL CHECK (return_status IN (1, 2, 3, 4, 5)),
    -- 1: Pending, 2: Approved, 3: Rejected, 4: Completed, 5: Cancelled
    return_admin_note        TEXT,
    return_shipping_provider VARCHAR(50),
    return_shipping_code     VARCHAR(100),
    return_shipping_note     TEXT,
    return_bank_name         VARCHAR(100),
    return_bank_account      VARCHAR(50),
    return_bank_account_name VARCHAR(100),
    return_created_at        TIMESTAMPTZ DEFAULT now() NOT NULL,
    return_updated_at        TIMESTAMPTZ DEFAULT now() NOT NULL
);

COMMENT ON COLUMN order_returns.return_status IS '1: Pending, 2: Approved, 3: Rejected, 4: Completed, 5: Cancelled';

CREATE INDEX idx_returns_order ON order_returns(return_order_id);
CREATE INDEX idx_returns_user ON order_returns(return_user_id, return_created_at DESC);
CREATE INDEX IF NOT EXISTS idx_order_returns_user_id ON order_returns(return_user_id);
CREATE INDEX idx_returns_status ON order_returns(return_status);
CREATE INDEX IF NOT EXISTS idx_returns_shipping_code ON order_returns(return_shipping_code);

-- Mỗi đơn hàng chỉ có tối đa 1 yêu cầu return đang active (Pending hoặc Approved)
CREATE UNIQUE INDEX idx_returns_active_per_order
    ON order_returns(return_order_id) WHERE return_status IN (1, 2);

CREATE OR REPLACE FUNCTION update_return_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.return_updated_at = now();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER set_return_updated_at
BEFORE UPDATE ON order_returns
FOR EACH ROW
EXECUTE FUNCTION update_return_updated_at();
