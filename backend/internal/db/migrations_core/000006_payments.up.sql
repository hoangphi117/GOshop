-- ============================================================
-- Payment Transaction History Table
-- Applicable to both Online (VNPay, MoMo) and COD.
-- One order can have multiple payment attempts.
-- ============================================================
CREATE TABLE IF NOT EXISTS payment_transactions (
    pt_id                INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pt_uuid              UUID DEFAULT gen_random_uuid() NOT NULL UNIQUE,

    pt_order_id          INT NOT NULL REFERENCES orders(order_id),

    -- Idempotency key do Frontend sinh (Online) hoặc auto-gen (COD).
    -- UNIQUE chống double-charge khi FE retry.
    pt_idempotency_key   VARCHAR(64) NOT NULL UNIQUE,

    -- Provider: 'vnpay', 'momo', 'cod'
    pt_provider          VARCHAR(20) NOT NULL,
    pt_txn_ref           VARCHAR(100) DEFAULT NULL, -- Mã merchant gửi gateway (ví dụ 260901-05-517W7S_1788231742)
    pt_provider_txn_id   VARCHAR(100) DEFAULT NULL, -- Mã giao dịch gateway (transId)
    pt_provider_url      TEXT DEFAULT NULL,          -- URL redirect (NULL cho COD)

    pt_amount            NUMERIC(14,2) NOT NULL CHECK (pt_amount > 0),
    pt_currency          VARCHAR(3) DEFAULT 'VND' NOT NULL,

    -- 1: Pending, 2: Paid, 3: Failed, 4: Expired, 5: Refunded
    pt_status            INT DEFAULT 1 CHECK (pt_status IN (1, 2, 3, 4, 5)) NOT NULL,

    -- Self-reference cho refund: trỏ về pt_id gốc đã Paid.
    -- NULL nếu đây là payment gốc (không phải refund).
    pt_refund_of         INT DEFAULT NULL REFERENCES payment_transactions(pt_id),
    pt_refund_amount     NUMERIC(14,2) DEFAULT NULL CHECK (pt_refund_amount IS NULL OR pt_refund_amount > 0),

    pt_paid_at           TIMESTAMPTZ DEFAULT NULL,
    pt_expired_at        TIMESTAMPTZ DEFAULT NULL,
    pt_metadata          JSONB DEFAULT '{}',

    pt_created_at        TIMESTAMPTZ DEFAULT now() NOT NULL,
    pt_updated_at        TIMESTAMPTZ DEFAULT now() NOT NULL
);

-- Reconciliation: Pending online over 15 minutes
CREATE INDEX idx_pt_pending_online ON payment_transactions(pt_status, pt_created_at)
    WHERE pt_status = 1 AND pt_provider != 'cod';

-- Lookup by order_id
CREATE INDEX idx_pt_order ON payment_transactions(pt_order_id, pt_status);

-- Lookup by txn_ref (Merchant gateway reference)
CREATE INDEX idx_pt_txn_ref ON payment_transactions(pt_provider, pt_txn_ref)
    WHERE pt_txn_ref IS NOT NULL;

-- Webhook lookup: tìm transaction theo provider_txn_id
CREATE INDEX idx_pt_provider_txn ON payment_transactions(pt_provider, pt_provider_txn_id)
    WHERE pt_provider_txn_id IS NOT NULL;

-- Lookup refund transactions by original transaction
CREATE INDEX idx_pt_refund_of ON payment_transactions(pt_refund_of)
    WHERE pt_refund_of IS NOT NULL;

COMMENT ON COLUMN payment_transactions.pt_status IS '1: Pending, 2: Paid, 3: Failed, 4: Expired, 5: Refunded';
COMMENT ON COLUMN payment_transactions.pt_provider IS 'vnpay, momo, cod';
COMMENT ON COLUMN payment_transactions.pt_refund_of IS 'Self-ref to original Paid pt_id for refund records';

-- Auto-update pt_updated_at
CREATE OR REPLACE FUNCTION update_pt_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.pt_updated_at = now();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER set_pt_updated_at
BEFORE UPDATE ON payment_transactions
FOR EACH ROW EXECUTE FUNCTION update_pt_updated_at();


-- ============================================================
-- Bảng dedup webhook events từ gateway (chỉ Online).
-- UNIQUE(we_provider, we_external_event_id) chống xử lý trùng.
-- ============================================================
CREATE TABLE IF NOT EXISTS webhook_events (
    we_id                INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    we_provider          VARCHAR(20) NOT NULL,
    we_external_event_id VARCHAR(100) NOT NULL,
    we_event_type        VARCHAR(50) NOT NULL,
    we_raw_body          TEXT NOT NULL,
    we_processed         BOOLEAN DEFAULT FALSE NOT NULL,
    we_received_at       TIMESTAMPTZ DEFAULT now() NOT NULL,

    CONSTRAINT uq_webhook_provider_event UNIQUE (we_provider, we_external_event_id)
);

CREATE INDEX idx_we_unprocessed ON webhook_events(we_processed, we_received_at)
    WHERE we_processed = FALSE;
