-- ============================================================
-- Product Reviews Table
-- ============================================================
CREATE TABLE IF NOT EXISTS product_reviews (
    review_id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    review_uuid        UUID DEFAULT gen_random_uuid() NOT NULL UNIQUE,
    review_user_id     INT NOT NULL,
    review_product_id  INT NOT NULL REFERENCES products(product_id) ON DELETE CASCADE,
    review_order_id    INT NOT NULL REFERENCES orders(order_id) ON DELETE CASCADE,
    review_rating      SMALLINT NOT NULL CHECK (review_rating BETWEEN 1 AND 5),
    review_title       VARCHAR(200),
    review_comment     TEXT,
    review_images      TEXT[] DEFAULT '{}' NOT NULL,
    review_video_url   TEXT,
    review_has_media   BOOLEAN DEFAULT false NOT NULL,
    review_status      SMALLINT DEFAULT 1 NOT NULL CHECK (review_status IN (1, 2, 3)),
    review_edit_count  INT DEFAULT 0 NOT NULL,
    review_helpful_count INT DEFAULT 0 NOT NULL,
    review_reply       TEXT DEFAULT NULL,
    review_reply_at    TIMESTAMPTZ DEFAULT NULL,
    review_created_at  TIMESTAMPTZ DEFAULT now() NOT NULL,
    review_updated_at  TIMESTAMPTZ DEFAULT now() NOT NULL
);

-- Helpful votes table
CREATE TABLE IF NOT EXISTS product_review_helpful_votes (
    vote_id     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    review_id   INT NOT NULL REFERENCES product_reviews(review_id) ON DELETE CASCADE,
    user_id     INT NOT NULL,
    created_at  TIMESTAMPTZ DEFAULT now() NOT NULL,
    CONSTRAINT uq_review_helpful_user UNIQUE(review_id, user_id)
);

-- Review reports table
CREATE TABLE IF NOT EXISTS product_review_reports (
    report_id    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    review_id    INT NOT NULL REFERENCES product_reviews(review_id) ON DELETE CASCADE,
    user_id      INT NOT NULL,
    user_name    VARCHAR(100) DEFAULT '' NOT NULL,
    user_email   VARCHAR(255) DEFAULT '' NOT NULL,
    reason       VARCHAR(50) NOT NULL, -- spam, inappropriate, fake, other
    details      TEXT,
    created_at   TIMESTAMPTZ DEFAULT now() NOT NULL,
    CONSTRAINT uq_review_report_user UNIQUE(review_id, user_id)
);

CREATE INDEX IF NOT EXISTS idx_review_reports_review ON product_review_reports(review_id);
CREATE INDEX IF NOT EXISTS idx_review_helpful_votes_review ON product_review_helpful_votes(review_id);
CREATE INDEX IF NOT EXISTS idx_product_reviews_user_id ON product_reviews(review_user_id);
CREATE INDEX IF NOT EXISTS idx_product_review_helpful_votes_user_id ON product_review_helpful_votes(user_id);
CREATE INDEX IF NOT EXISTS idx_product_review_reports_user_id ON product_review_reports(user_id);

COMMENT ON COLUMN product_reviews.review_status IS '1: Visible, 2: Hidden, 3: Reported';

-- Alter products table to store aggregate rating metrics
ALTER TABLE products
    ADD COLUMN IF NOT EXISTS product_avg_rating NUMERIC(2,1) DEFAULT 0.0 NOT NULL,
    ADD COLUMN IF NOT EXISTS product_review_count INT DEFAULT 0 NOT NULL;

-- Indexes
CREATE INDEX idx_reviews_product ON product_reviews(review_product_id, review_status, review_created_at DESC);
CREATE INDEX idx_reviews_user ON product_reviews(review_user_id, review_created_at DESC);
CREATE INDEX idx_reviews_product_filter ON product_reviews(review_product_id, review_status, review_rating, review_has_media, review_created_at DESC);

-- Unique constraint: 1 user can only review a product once per order
CREATE UNIQUE INDEX idx_reviews_unique_per_order 
ON product_reviews(review_user_id, review_product_id, review_order_id);

-- Trigger auto update review_updated_at
CREATE OR REPLACE FUNCTION set_review_updated_at_fn()
RETURNS TRIGGER AS $$
BEGIN
    NEW.review_updated_at = now();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER set_review_updated_at
    BEFORE UPDATE ON product_reviews
    FOR EACH ROW
    EXECUTE FUNCTION set_review_updated_at_fn();
