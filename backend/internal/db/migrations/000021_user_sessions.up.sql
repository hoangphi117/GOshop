CREATE TABLE IF NOT EXISTS user_sessions (
    session_id      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_uuid    UUID DEFAULT gen_random_uuid() NOT NULL UNIQUE,
    user_id         INT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    family_id       VARCHAR(64) NOT NULL UNIQUE,
    ip_address      VARCHAR(45),
    user_agent      TEXT,
    device_name     VARCHAR(200),
    last_active_at  TIMESTAMPTZ DEFAULT now() NOT NULL,
    created_at      TIMESTAMPTZ DEFAULT now() NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_sessions_user_id ON user_sessions(user_id);
CREATE INDEX IF NOT EXISTS idx_sessions_family_id ON user_sessions(family_id);
