-- Orders (Đơn hàng)
CREATE TABLE IF NOT EXISTS orders (
    order_id                INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_uuid              UUID DEFAULT gen_random_uuid() NOT NULL UNIQUE,
    order_number            VARCHAR(20) NOT NULL UNIQUE,

    order_user_id           INT NOT NULL,
    order_user_uuid         UUID NOT NULL DEFAULT '00000000-0000-0000-0000-000000000000',
    order_customer_name     VARCHAR(100) NOT NULL DEFAULT '',
    order_customer_email    VARCHAR(255) NOT NULL DEFAULT '',

    order_shipping_name     VARCHAR(100) NOT NULL,
    order_shipping_phone    VARCHAR(20) NOT NULL,
    order_shipping_address  TEXT NOT NULL,

    order_total_amount      NUMERIC(14,2) NOT NULL CHECK (order_total_amount >= 0),
    order_refunded_amount   NUMERIC(14,2) DEFAULT 0.00 NOT NULL CHECK (order_refunded_amount >= 0),

    order_payment_method    INT DEFAULT 1 CHECK (order_payment_method IN (1, 2, 3)) NOT NULL,
    -- 1: COD, 2: Bank Transfer, 3: E-Wallet
    order_payment_status    INT DEFAULT 1 CHECK (order_payment_status IN (1, 2, 3, 4)) NOT NULL,
    -- 1: Unpaid, 2: Paid, 3: Partially Refunded, 4: Refunded

    order_note              TEXT,
    order_status            INT DEFAULT 1 CHECK (order_status IN (1, 2, 3, 4, 5, 6)) NOT NULL,
    -- 1: Pending, 2: Confirmed, 3: Shipped, 4: Delivered, 5: Cancelled, 6: Returned

    order_cancelled_at      TIMESTAMPTZ DEFAULT NULL,
    order_created_at        TIMESTAMPTZ DEFAULT now() NOT NULL,
    order_updated_at        TIMESTAMPTZ DEFAULT now() NOT NULL
);

-- Order Details
CREATE TABLE IF NOT EXISTS order_items (
    order_item_id            INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_item_uuid          UUID DEFAULT gen_random_uuid() NOT NULL UNIQUE,
    order_item_order_id      INT NOT NULL REFERENCES orders(order_id) ON DELETE CASCADE,
    order_item_product_id    INT NOT NULL REFERENCES products(product_id),
    order_item_product_name  VARCHAR(200) NOT NULL,
    order_item_price         NUMERIC(12,2) NOT NULL CHECK (order_item_price > 0),
    order_item_quantity      INT NOT NULL CHECK (order_item_quantity > 0),
    order_item_subtotal      NUMERIC(14,2) NOT NULL CHECK (order_item_subtotal > 0),
    order_item_created_at    TIMESTAMPTZ DEFAULT now() NOT NULL
);

COMMENT ON COLUMN orders.order_status IS '1: Pending, 2: Confirmed, 3: Shipped, 4: Delivered, 5: Cancelled, 6: Returned';
COMMENT ON COLUMN orders.order_payment_method IS '1: COD, 2: Bank Transfer, 3: E-Wallet';
COMMENT ON COLUMN orders.order_payment_status IS '1: Unpaid, 2: Paid, 3: Partially Refunded, 4: Refunded';

CREATE INDEX idx_orders_user ON orders(order_user_id, order_status, order_created_at DESC);
CREATE INDEX IF NOT EXISTS idx_orders_order_user_id ON orders(order_user_id);
CREATE INDEX idx_orders_user_uuid ON orders(order_user_uuid);
CREATE INDEX idx_orders_status ON orders(order_status, order_created_at DESC);
CREATE INDEX idx_orders_number ON orders(order_number);
CREATE INDEX idx_order_items_order ON order_items(order_item_order_id);

CREATE OR REPLACE FUNCTION update_order_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.order_updated_at = now();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER set_order_updated_at
BEFORE UPDATE ON orders
FOR EACH ROW
EXECUTE FUNCTION update_order_updated_at();