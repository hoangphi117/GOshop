-- Stock Movements
CREATE TABLE IF NOT EXISTS stock_movements (
    movement_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    movement_uuid     UUID DEFAULT gen_random_uuid() NOT NULL UNIQUE,
    product_id        INT NOT NULL REFERENCES products(product_id) ON DELETE CASCADE,
    change_type       VARCHAR(30) NOT NULL,
    quantity_change   INT NOT NULL,
    stock_before      INT NOT NULL,
    stock_after       INT NOT NULL,
    reference_id      VARCHAR(100),
    reference_type    VARCHAR(30),
    actor_id          INT REFERENCES users(user_id) ON DELETE SET NULL,
    note              TEXT,
    created_at        TIMESTAMPTZ DEFAULT now() NOT NULL
);

COMMENT ON COLUMN stock_movements.change_type IS 'ORDER_PLACED, ORDER_CANCELLED, ORDER_RETURNED, RESTOCK, MANUAL_ADJUSTMENT, INITIAL_STOCK, DAMAGED_DISCARD';
COMMENT ON COLUMN stock_movements.reference_type IS 'order, return, manual, product_edit';

-- Indexes
CREATE INDEX IF NOT EXISTS idx_stock_movements_product_created ON stock_movements(product_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_stock_movements_type_created ON stock_movements(change_type, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_stock_movements_reference ON stock_movements(reference_type, reference_id);
CREATE INDEX IF NOT EXISTS idx_stock_movements_created ON stock_movements(created_at DESC);
