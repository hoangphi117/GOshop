-- Coupons
CREATE TABLE IF NOT EXISTS coupons (
    coupon_id                  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    coupon_uuid                UUID DEFAULT gen_random_uuid() NOT NULL UNIQUE,
    coupon_code                VARCHAR(50) NOT NULL UNIQUE, -- always uppercase, no spaces, no special characters, e.g. "SUMMER2023"
    coupon_name                VARCHAR(100) NOT NULL,
    coupon_description         TEXT,
    coupon_type                INT NOT NULL CHECK (coupon_type IN (1, 2)), -- 1: Percentage, 2: Fixed Amount
    coupon_discount_value      NUMERIC(14,2) NOT NULL CHECK (coupon_discount_value > 0),
    coupon_max_discount_amount NUMERIC(14,2) DEFAULT NULL,
    coupon_min_order_amount    NUMERIC(14,2) DEFAULT 0.00 NOT NULL,
    coupon_usage_limit         INT DEFAULT NULL,
    coupon_used_count          INT DEFAULT 0 NOT NULL,
    coupon_user_usage_limit    INT DEFAULT 1 NOT NULL,
    coupon_start_date          TIMESTAMPTZ NOT NULL,
    coupon_end_date            TIMESTAMPTZ NOT NULL,
    coupon_is_active           BOOLEAN DEFAULT TRUE NOT NULL,
    coupon_deleted_at          TIMESTAMPTZ DEFAULT NULL, -- soft-delete
    coupon_created_at          TIMESTAMPTZ DEFAULT now() NOT NULL,
    coupon_updated_at          TIMESTAMPTZ DEFAULT now() NOT NULL,
    CONSTRAINT check_coupon_dates CHECK (coupon_end_date > coupon_start_date)
);

-- Coupon Usages — Usage history
CREATE TABLE IF NOT EXISTS coupon_usages (
    coupon_usage_id        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    coupon_usage_coupon_id INT NOT NULL REFERENCES coupons(coupon_id),
    coupon_usage_user_id   INT NOT NULL,
    coupon_usage_order_id  INT DEFAULT NULL REFERENCES orders(order_id) ON DELETE SET NULL,
    coupon_usage_used_at   TIMESTAMPTZ DEFAULT now() NOT NULL
);

CREATE INDEX idx_coupon_usages_user ON coupon_usages(coupon_usage_coupon_id, coupon_usage_user_id);
CREATE INDEX IF NOT EXISTS idx_coupon_usages_user_id ON coupon_usages(coupon_usage_user_id);
-- Prevent applying the same coupon to the same order multiple times
CREATE UNIQUE INDEX IF NOT EXISTS uq_coupon_usages_coupon_order 
ON coupon_usages (coupon_usage_coupon_id, coupon_usage_order_id) 
WHERE coupon_usage_order_id IS NOT NULL;
CREATE INDEX idx_coupons_active_dates ON coupons(coupon_is_active, coupon_start_date, coupon_end_date)
    WHERE coupon_deleted_at IS NULL;

-- Trigger auto update coupon_updated_at
CREATE OR REPLACE FUNCTION update_coupon_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.coupon_updated_at = now();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER set_coupon_updated_at
BEFORE UPDATE ON coupons
FOR EACH ROW EXECUTE FUNCTION update_coupon_updated_at();

-- Add columns to the orders table to store coupon information
ALTER TABLE orders
    ADD COLUMN order_coupon_id       INT DEFAULT NULL REFERENCES coupons(coupon_id),
    ADD COLUMN order_coupon_code     VARCHAR(50) DEFAULT NULL, -- Snapshot 
    ADD COLUMN order_subtotal_amount NUMERIC(14,2), -- total amount before applying coupon discount, can be NULL for old orders
    ADD COLUMN order_discount_amount NUMERIC(14,2) DEFAULT 0.00 NOT NULL;

-- Backfill order_subtotal_amount = order_total_amount cho các đơn cũ
UPDATE orders SET order_subtotal_amount = order_total_amount WHERE order_subtotal_amount IS NULL;
ALTER TABLE orders ALTER COLUMN order_subtotal_amount SET NOT NULL;
