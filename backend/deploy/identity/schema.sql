-- =============================================================================
-- GOSHOP IDENTITY SERVICE INDEPENDENT DATABASE SCHEMA
-- Target Database: goshop_identity
-- Purpose: Complete standalone database schema for the decoupled Identity Service
-- =============================================================================

CREATE EXTENSION IF NOT EXISTS "pgcrypto";
CREATE EXTENSION IF NOT EXISTS "unaccent";

-- -----------------------------------------------------------------------------
-- 1. USERS TABLE
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS users (
    user_id             INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_uuid           UUID DEFAULT gen_random_uuid() NOT NULL UNIQUE,
    user_fullname       VARCHAR(100) NOT NULL,
    user_email          VARCHAR(150) UNIQUE NOT NULL,
    user_password       VARCHAR(90) DEFAULT NULL, -- NULL allowed for pure OAuth users
    user_age            INT CHECK (user_age >= 1 AND user_age <= 150),
    user_status         INT DEFAULT 1 CHECK (user_status IN (1, 2, 3)) NOT NULL,
    -- 1: Active, 2: Inactive, 3: Banned
    user_level          INT DEFAULT 1 CHECK (user_level IN (1, 2, 3)) NOT NULL,
    -- 1: Admin, 2: Moderator, 3: Member
    user_oauth_provider VARCHAR(30) DEFAULT NULL,
    user_oauth_id       VARCHAR(200) DEFAULT NULL,
    user_avatar_url     TEXT DEFAULT NULL,
    user_deleted_at     TIMESTAMPTZ DEFAULT NULL,
    user_created_at     TIMESTAMPTZ DEFAULT now() NOT NULL,
    user_updated_at     TIMESTAMPTZ DEFAULT now() NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_users_level ON users(user_level);
CREATE INDEX IF NOT EXISTS idx_users_status ON users(user_status);
CREATE INDEX IF NOT EXISTS idx_users_created_at ON users(user_created_at);
CREATE INDEX IF NOT EXISTS idx_users_deleted_at ON users(user_deleted_at);
CREATE INDEX IF NOT EXISTS idx_users_email_status ON users(user_email, user_status);
CREATE UNIQUE INDEX IF NOT EXISTS idx_users_oauth
    ON users(user_oauth_provider, user_oauth_id)
    WHERE user_oauth_provider IS NOT NULL;

CREATE OR REPLACE FUNCTION update_user_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.user_updated_at = now();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS set_user_updated_at ON users;
CREATE TRIGGER set_user_updated_at
BEFORE UPDATE ON users
FOR EACH ROW
EXECUTE FUNCTION update_user_updated_at();

-- -----------------------------------------------------------------------------
-- 2. USER ADDRESSES TABLE
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS user_addresses (
    ua_id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ua_uuid       UUID DEFAULT gen_random_uuid() NOT NULL UNIQUE,
    ua_user_id    INT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    ua_label      VARCHAR(50) NOT NULL,
    ua_name       VARCHAR(100) NOT NULL,
    ua_phone      VARCHAR(20) NOT NULL,
    ua_address    TEXT NOT NULL,
    ua_is_default BOOLEAN DEFAULT FALSE NOT NULL,
    ua_created_at TIMESTAMPTZ DEFAULT now() NOT NULL,
    ua_updated_at TIMESTAMPTZ DEFAULT now() NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_user_addresses_user_id ON user_addresses(ua_user_id);
CREATE UNIQUE INDEX IF NOT EXISTS idx_user_addresses_one_default 
    ON user_addresses(ua_user_id) 
    WHERE ua_is_default = TRUE;

CREATE OR REPLACE FUNCTION set_ua_updated_at_fn()
RETURNS TRIGGER AS $$
BEGIN
    NEW.ua_updated_at = now();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS set_ua_updated_at ON user_addresses;
CREATE TRIGGER set_ua_updated_at
    BEFORE UPDATE ON user_addresses
    FOR EACH ROW
    EXECUTE FUNCTION set_ua_updated_at_fn();

-- -----------------------------------------------------------------------------
-- 3. USER SESSIONS TABLE (Persistent Refresh Tokens & Session Auditing)
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS user_sessions (
    session_id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_uuid       UUID DEFAULT gen_random_uuid() NOT NULL UNIQUE,
    user_uuid          UUID NOT NULL,
    family_id          VARCHAR(64) NOT NULL,
    refresh_token_hash VARCHAR(64) NOT NULL UNIQUE,
    ip_address         VARCHAR(45),
    user_agent         TEXT,
    is_revoked         BOOLEAN DEFAULT FALSE NOT NULL,
    expires_at         TIMESTAMPTZ NOT NULL,
    created_at         TIMESTAMPTZ DEFAULT now() NOT NULL,
    updated_at         TIMESTAMPTZ DEFAULT now() NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_user_sessions_user_uuid ON user_sessions(user_uuid);
CREATE INDEX IF NOT EXISTS idx_user_sessions_family_id ON user_sessions(family_id);
CREATE INDEX IF NOT EXISTS idx_user_sessions_expires_at ON user_sessions(expires_at);
