CREATE TABLE IF NOT EXISTS notifications (
    notification_id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    notification_uuid       UUID DEFAULT gen_random_uuid() NOT NULL UNIQUE,
    notification_user_id    INT NOT NULL,
    notification_type       VARCHAR(50) NOT NULL,
    notification_title      VARCHAR(255) NOT NULL,
    notification_body       TEXT NOT NULL,
    notification_data       JSONB DEFAULT '{}'::jsonb,
    notification_is_read    BOOLEAN DEFAULT FALSE NOT NULL,
    notification_read_at    TIMESTAMPTZ,
    notification_created_at TIMESTAMPTZ DEFAULT now() NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_notifications_user_unread
    ON notifications(notification_user_id, notification_is_read, notification_created_at DESC);

CREATE INDEX IF NOT EXISTS idx_notifications_user_all
    ON notifications(notification_user_id, notification_created_at DESC);

CREATE INDEX IF NOT EXISTS idx_notifications_user_id 
    ON notifications(notification_user_id);
