-- =============================================================================
-- Product Variants (SKU-level)
-- =============================================================================

CREATE TABLE IF NOT EXISTS product_variants (
    variant_id              INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    variant_uuid            UUID DEFAULT gen_random_uuid() NOT NULL UNIQUE,
    product_id              INT NOT NULL REFERENCES products(product_id) ON DELETE CASCADE,
    variant_sku             VARCHAR(100) NOT NULL UNIQUE,
    variant_title           VARCHAR(255) NOT NULL,
    variant_price           NUMERIC(12,2) NOT NULL CHECK (variant_price > 0),
    variant_compare_at_price NUMERIC(12,2),
    variant_image_url       TEXT,
    -- Flexible attribute map, e.g. {"Color":"Blue","Storage":"256GB"}
    variant_attributes      JSONB NOT NULL DEFAULT '{}',
    variant_position        INT NOT NULL DEFAULT 0,
    -- 1: Active, 2: Inactive
    variant_status          INT NOT NULL DEFAULT 1 CHECK (variant_status IN (1, 2)),
    variant_created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    variant_updated_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);

COMMENT ON TABLE  product_variants IS 'SKU-level product variants (colour, size, storage, etc.)';
COMMENT ON COLUMN product_variants.variant_attributes IS 'Free-form key/value option map, e.g. {"Color":"Blue","Size":"XL"}';
COMMENT ON COLUMN product_variants.variant_status     IS '1: Active, 2: Inactive';

-- Indexes
CREATE INDEX IF NOT EXISTS idx_variants_product_id
    ON product_variants (product_id, variant_position, variant_id);

CREATE INDEX IF NOT EXISTS idx_variants_uuid
    ON product_variants (variant_uuid);

CREATE UNIQUE INDEX IF NOT EXISTS idx_variants_sku_unique
    ON product_variants (LOWER(variant_sku));

-- Auto-update variant_updated_at
CREATE OR REPLACE FUNCTION update_variant_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.variant_updated_at = now();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER set_variant_updated_at
BEFORE UPDATE ON product_variants
FOR EACH ROW
EXECUTE FUNCTION update_variant_updated_at();
