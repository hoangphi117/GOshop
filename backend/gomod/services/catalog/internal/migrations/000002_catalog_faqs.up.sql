-- FAQ knowledge base for the shopping assistant.
--
-- Rows are the source of truth; the assistant searches them through
-- Meilisearch (second index, same client). Keeping them in the catalog DB
-- means a FAQ edit ships with the same migration cycle as products.
CREATE TABLE IF NOT EXISTS catalog_faqs (
    faq_id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    faq_uuid       UUID DEFAULT gen_random_uuid() NOT NULL UNIQUE,
    question       TEXT NOT NULL,
    answer         TEXT NOT NULL,
    tags           TEXT[] NOT NULL DEFAULT '{}',
    is_active      BOOLEAN NOT NULL DEFAULT TRUE,
    faq_created_at TIMESTAMPTZ DEFAULT now() NOT NULL,
    faq_updated_at TIMESTAMPTZ DEFAULT now() NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_catalog_faqs_active ON catalog_faqs(is_active);
CREATE INDEX IF NOT EXISTS idx_catalog_faqs_tags ON catalog_faqs USING GIN(tags);

CREATE TRIGGER set_faq_updated_at
BEFORE UPDATE ON catalog_faqs
FOR EACH ROW
EXECUTE FUNCTION update_catalog_updated_at();

