-- Assistant transcript. Replaces the Redis session store, which kept only
-- role+content and therefore lost the product cards on reload.
--
-- One row per message rather than a conversations table: the widget only ever
-- asks for "the newest conversation of this user", and a join would not buy
-- anything for that query.
CREATE TABLE IF NOT EXISTS assistant_messages (
    message_id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_uuid UUID NOT NULL,
    -- No FK: identity service owns the user table.
    user_id           INT NOT NULL,
    role              VARCHAR(10) NOT NULL,
    content           TEXT NOT NULL,
    -- Product cards carried by an assistant turn; empty for user turns.
    products          JSONB NOT NULL DEFAULT '[]'::jsonb,
    fallback_to_human BOOLEAN NOT NULL DEFAULT FALSE,
    created_at        TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Load one conversation in insertion order.
CREATE INDEX IF NOT EXISTS idx_assistant_msg_conv
    ON assistant_messages(conversation_uuid, message_id);

-- Latest() looks up the newest conversation_uuid for a user, so it needs the
-- user_id prefix and a descending message_id.
CREATE INDEX IF NOT EXISTS idx_assistant_msg_user
    ON assistant_messages(user_id, message_id DESC);

-- Retention sweep deletes by age.
CREATE INDEX IF NOT EXISTS idx_assistant_msg_created
    ON assistant_messages(created_at);