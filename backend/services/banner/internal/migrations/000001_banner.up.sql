-- Banners moved out of the monolith (see monolith-extraction plan).
-- Schema mirrors the monolith's banners table so `seed` data can be copied 1:1.
CREATE TABLE IF NOT EXISTS banners (
    banner_id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    banner_uuid       UUID DEFAULT gen_random_uuid() NOT NULL UNIQUE,
    banner_title      VARCHAR(255) NOT NULL,
    banner_image_url  TEXT NOT NULL,
    banner_link_url   TEXT,
    banner_position   VARCHAR(50) DEFAULT 'home_main' NOT NULL,
    banner_order      INT DEFAULT 0 NOT NULL,
    banner_is_active  BOOLEAN DEFAULT TRUE NOT NULL,
    banner_start_at   TIMESTAMPTZ,
    banner_end_at     TIMESTAMPTZ,
    banner_deleted_at TIMESTAMPTZ,
    banner_created_at TIMESTAMPTZ DEFAULT now() NOT NULL,
    banner_updated_at TIMESTAMPTZ DEFAULT now() NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_banners_position_active ON banners (banner_position, banner_is_active, banner_order ASC);
CREATE INDEX IF NOT EXISTS idx_banners_uuid ON banners (banner_uuid);
