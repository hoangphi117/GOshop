-- Chat domain tables. Extracted from the monolith core schema; chat data is
-- not rebuildable, so the monolith copy stays intact until the release
-- cycle confirms the move.
CREATE TABLE IF NOT EXISTS chat_conversations (
    conversation_id   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_uuid UUID DEFAULT gen_random_uuid() NOT NULL UNIQUE,
    user_id           INT NOT NULL,
    admin_id          INT,
    user_fullname     VARCHAR(100) NOT NULL DEFAULT '',
    user_email        VARCHAR(255) NOT NULL DEFAULT '',
    user_avatar       TEXT NOT NULL DEFAULT '',
    status            VARCHAR(20) NOT NULL DEFAULT 'open',
    last_message_at   TIMESTAMPTZ,
    created_at        TIMESTAMPTZ DEFAULT now() NOT NULL,
    updated_at        TIMESTAMPTZ DEFAULT now() NOT NULL
);

CREATE TABLE IF NOT EXISTS chat_messages (
    message_id        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    message_uuid      UUID DEFAULT gen_random_uuid() NOT NULL UNIQUE,
    conversation_id   INT NOT NULL REFERENCES chat_conversations(conversation_id) ON DELETE CASCADE,
    sender_id         INT NOT NULL,
    sender_role       VARCHAR(10) NOT NULL,
    content           TEXT NOT NULL,
    content_type      VARCHAR(20) NOT NULL DEFAULT 'text',
    attachment_url    TEXT,
    attachment_name   TEXT,
    attachment_size   BIGINT,
    is_read           BOOLEAN NOT NULL DEFAULT FALSE,
    read_at           TIMESTAMPTZ,
    created_at        TIMESTAMPTZ DEFAULT now() NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_chat_conv_admin ON chat_conversations(admin_id, status, last_message_at DESC);
CREATE INDEX IF NOT EXISTS idx_chat_conv_user ON chat_conversations(user_id, last_message_at DESC);
CREATE INDEX IF NOT EXISTS idx_chat_conversations_user_id ON chat_conversations(user_id);
CREATE INDEX IF NOT EXISTS idx_chat_conversations_admin_id ON chat_conversations(admin_id);
CREATE INDEX IF NOT EXISTS idx_chat_msg_conv ON chat_messages(conversation_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_chat_messages_sender_id ON chat_messages(sender_id);
CREATE INDEX IF NOT EXISTS idx_chat_msg_unread ON chat_messages(conversation_id, is_read) WHERE is_read = FALSE;
CREATE INDEX IF NOT EXISTS idx_chat_msg_id_desc ON chat_messages(conversation_id, message_id DESC);
