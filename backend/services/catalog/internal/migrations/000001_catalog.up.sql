-- Categories
CREATE TABLE IF NOT EXISTS categories (
    category_id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_uuid        UUID DEFAULT gen_random_uuid() NOT NULL UNIQUE,
    category_name        VARCHAR(100) NOT NULL,
    category_slug        VARCHAR(100) NOT NULL UNIQUE,
    category_description TEXT,
    category_status      INT DEFAULT 1 CHECK (category_status IN (1, 2)) NOT NULL,
    category_deleted_at  TIMESTAMPTZ DEFAULT NULL,
    category_created_at  TIMESTAMPTZ DEFAULT now() NOT NULL,
    category_updated_at  TIMESTAMPTZ DEFAULT now() NOT NULL
);

-- Products
CREATE TABLE IF NOT EXISTS products (
    product_id           INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_uuid         UUID DEFAULT gen_random_uuid() NOT NULL UNIQUE,
    product_name         VARCHAR(200) NOT NULL,
    product_slug         VARCHAR(200) NOT NULL UNIQUE,
    product_description  TEXT,
    product_price        NUMERIC(12,2) NOT NULL CHECK (product_price > 0),
    product_sku          VARCHAR(50) UNIQUE,
    product_category_id  INT NOT NULL REFERENCES categories(category_id),
    product_image_url    TEXT,
    product_status       INT DEFAULT 1 CHECK (product_status IN (1, 2, 3)) NOT NULL,
    product_deleted_at   TIMESTAMPTZ DEFAULT NULL,
    product_created_at   TIMESTAMPTZ DEFAULT now() NOT NULL,
    product_updated_at   TIMESTAMPTZ DEFAULT now() NOT NULL,
    product_avg_rating   NUMERIC(2,1) DEFAULT 0.0 NOT NULL,
    product_review_count INT DEFAULT 0 NOT NULL
);

COMMENT ON COLUMN products.product_status IS '1: Active, 2: Inactive, 3: Out of Stock';
COMMENT ON COLUMN categories.category_status IS '1: Active, 2: Inactive';

-- Indexes for Categories
CREATE INDEX IF NOT EXISTS idx_categories_list ON categories(category_deleted_at, category_created_at DESC);
CREATE INDEX IF NOT EXISTS idx_categories_slug ON categories(category_slug);
CREATE UNIQUE INDEX IF NOT EXISTS idx_categories_name_unique 
ON categories (LOWER(category_name)) 
WHERE category_deleted_at IS NULL;

-- Indexes for Products
CREATE UNIQUE INDEX IF NOT EXISTS idx_products_name_category_unique
ON products (LOWER(product_name), product_category_id)
WHERE product_deleted_at IS NULL;

CREATE INDEX IF NOT EXISTS idx_products_list ON products(product_deleted_at, product_category_id, product_status, product_created_at DESC);
CREATE INDEX IF NOT EXISTS idx_products_slug ON products(product_slug);

-- Triggers for updated_at
CREATE OR REPLACE FUNCTION update_catalog_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.category_updated_at = now();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE OR REPLACE FUNCTION update_product_catalog_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.product_updated_at = now();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER set_category_updated_at
BEFORE UPDATE ON categories
FOR EACH ROW
EXECUTE FUNCTION update_catalog_updated_at();

CREATE TRIGGER set_product_updated_at
BEFORE UPDATE ON products
FOR EACH ROW
EXECUTE FUNCTION update_product_catalog_updated_at();

-- Outbox Events for Search & Worker integration
CREATE TABLE IF NOT EXISTS outbox_events (
    event_id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    aggregate_type  VARCHAR(64) NOT NULL,
    aggregate_id    VARCHAR(64) NOT NULL,
    event_type      VARCHAR(64) NOT NULL,
    payload         JSONB NOT NULL,
    status          VARCHAR(16) DEFAULT 'PENDING' NOT NULL,
    created_at      TIMESTAMPTZ DEFAULT now() NOT NULL,
    processed_at    TIMESTAMPTZ
);

CREATE INDEX IF NOT EXISTS idx_outbox_events_status_created 
ON outbox_events (status, created_at);
