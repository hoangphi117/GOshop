-- Order Service Database Migration

CREATE EXTENSION IF NOT EXISTS "unaccent";

CREATE SCHEMA IF NOT EXISTS orders;

SET search_path TO orders, public;

CREATE OR REPLACE FUNCTION update_order_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.order_updated_at = now();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE OR REPLACE FUNCTION update_return_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.return_updated_at = now();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TABLE IF NOT EXISTS orders.orders (
    order_id                INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_uuid              UUID DEFAULT gen_random_uuid() NOT NULL UNIQUE,
    order_number            VARCHAR(20) NOT NULL UNIQUE,
    order_user_id           INT NOT NULL,
    order_user_uuid         UUID DEFAULT '00000000-0000-0000-0000-000000000000'::uuid NOT NULL,
    order_customer_name     VARCHAR(100) DEFAULT ''::character varying NOT NULL,
    order_customer_email    VARCHAR(255) DEFAULT ''::character varying NOT NULL,
    order_shipping_name     VARCHAR(100) NOT NULL,
    order_shipping_phone    VARCHAR(20) NOT NULL,
    order_shipping_address  TEXT NOT NULL,
    order_total_amount      NUMERIC(14,2) NOT NULL CHECK (order_total_amount >= 0),
    order_refunded_amount   NUMERIC(14,2) DEFAULT 0.00 NOT NULL CHECK (order_refunded_amount >= 0),
    order_payment_method    INT DEFAULT 1 NOT NULL CHECK (order_payment_method IN (1, 2, 3)),
    order_payment_status    INT DEFAULT 1 NOT NULL CHECK (order_payment_status IN (1, 2, 3, 4)),
    order_note              TEXT,
    order_status            INT DEFAULT 1 NOT NULL CHECK (order_status IN (1, 2, 3, 4, 5, 6)),
    order_cancelled_at      TIMESTAMPTZ,
    order_created_at        TIMESTAMPTZ DEFAULT now() NOT NULL,
    order_updated_at        TIMESTAMPTZ DEFAULT now() NOT NULL,
    order_coupon_id         INT,
    order_coupon_code       VARCHAR(50),
    order_subtotal_amount   NUMERIC(14,2) NOT NULL,
    order_discount_amount   NUMERIC(14,2) DEFAULT 0.00 NOT NULL,
    order_shipping_provider VARCHAR(20),
    order_shipping_code     VARCHAR(50),
    order_shipping_fee      NUMERIC(12,2) DEFAULT 0.00 NOT NULL,
    order_expected_delivery TIMESTAMPTZ,
    order_delivered_at      TIMESTAMPTZ,
    order_returned_at       TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS orders.order_items (
    order_item_id                INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_item_uuid              UUID DEFAULT gen_random_uuid() NOT NULL UNIQUE,
    order_item_order_id          INT NOT NULL REFERENCES orders.orders(order_id) ON DELETE CASCADE,
    order_item_order_uuid        UUID DEFAULT '00000000-0000-0000-0000-000000000000'::uuid NOT NULL,
    order_item_product_id        INT NOT NULL,
    order_item_product_uuid      UUID DEFAULT '00000000-0000-0000-0000-000000000000'::uuid NOT NULL,
    order_item_product_name      VARCHAR(200) NOT NULL,
    order_item_product_slug      VARCHAR(255) DEFAULT ''::character varying NOT NULL,
    order_item_product_image_url TEXT,
    order_item_price             NUMERIC(12,2) NOT NULL CHECK (order_item_price > 0),
    order_item_quantity          INT NOT NULL CHECK (order_item_quantity > 0),
    order_item_subtotal          NUMERIC(14,2) NOT NULL CHECK (order_item_subtotal > 0),
    order_item_created_at        TIMESTAMPTZ DEFAULT now() NOT NULL
);

CREATE TABLE IF NOT EXISTS orders.order_tracking_events (
    event_id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_order_id   INT NOT NULL REFERENCES orders.orders(order_id) ON DELETE CASCADE,
    event_status     VARCHAR(50) NOT NULL,
    event_note       TEXT,
    event_source     VARCHAR(20) DEFAULT 'system'::character varying NOT NULL,
    event_created_at TIMESTAMPTZ DEFAULT now() NOT NULL
);

CREATE TABLE IF NOT EXISTS orders.order_returns (
    return_id                INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    return_uuid              UUID DEFAULT gen_random_uuid() NOT NULL UNIQUE,
    return_order_id          INT NOT NULL REFERENCES orders.orders(order_id) ON DELETE CASCADE,
    return_user_id           INT NOT NULL,
    return_reason            TEXT NOT NULL,
    return_status            SMALLINT DEFAULT 1 NOT NULL CHECK (return_status IN (1, 2, 3, 4, 5)),
    return_admin_note        TEXT,
    return_created_at        TIMESTAMPTZ DEFAULT now() NOT NULL,
    return_updated_at        TIMESTAMPTZ DEFAULT now() NOT NULL,
    return_images            TEXT[] DEFAULT '{}'::text[] NOT NULL,
    return_video_url         TEXT,
    return_shipping_provider VARCHAR(50),
    return_shipping_code     VARCHAR(100),
    return_shipping_note     TEXT,
    return_bank_name         VARCHAR(100),
    return_bank_account      VARCHAR(50),
    return_bank_account_name VARCHAR(100)
);

CREATE TABLE IF NOT EXISTS orders.order_sagas (
    order_uuid       UUID PRIMARY KEY,
    user_uuid        UUID NOT NULL,
    idempotency_key  VARCHAR(100) NOT NULL,
    state            VARCHAR(20) NOT NULL DEFAULT 'STARTED',
    last_step        VARCHAR(30),
    payload          JSONB NOT NULL,
    snapshot         JSONB,
    failure_reason   TEXT,
    attempts         INT NOT NULL DEFAULT 0,
    next_retry_at    TIMESTAMPTZ,
    created_at       TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at       TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT chk_saga_state CHECK (state IN ('STARTED', 'COMPENSATING', 'CONFIRMED', 'FAILED')),
    CONSTRAINT uq_saga_idem   UNIQUE (user_uuid, idempotency_key)
);

CREATE TABLE IF NOT EXISTS orders.outbox_events (
    event_id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    aggregate_type  VARCHAR(50) DEFAULT '' NOT NULL,
    aggregate_id    VARCHAR(100) DEFAULT '' NOT NULL,
    event_type      VARCHAR(50) DEFAULT '' NOT NULL,
    payload         JSONB DEFAULT '{}'::jsonb NOT NULL,
    status          VARCHAR(20) DEFAULT 'PENDING' NOT NULL,
    retry_count     INT DEFAULT 0 NOT NULL,
    last_error      TEXT,
    created_at      TIMESTAMPTZ DEFAULT now() NOT NULL,
    processed_at    TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS orders.webhook_events (
    we_id                INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    we_provider          VARCHAR(20) NOT NULL,
    we_external_event_id VARCHAR(100) NOT NULL,
    we_event_type        VARCHAR(50) NOT NULL,
    we_raw_body          TEXT NOT NULL,
    we_processed         BOOLEAN DEFAULT false NOT NULL,
    we_received_at       TIMESTAMPTZ DEFAULT now() NOT NULL,
    we_created_at        TIMESTAMPTZ DEFAULT now() NOT NULL,
    CONSTRAINT uq_webhook_provider_event UNIQUE (we_provider, we_external_event_id)
);

-- Indexes
CREATE INDEX IF NOT EXISTS idx_orders_user ON orders.orders (order_user_id, order_status, order_created_at DESC);
CREATE INDEX IF NOT EXISTS idx_orders_order_user_id ON orders.orders (order_user_id);
CREATE INDEX IF NOT EXISTS idx_orders_status ON orders.orders (order_status, order_created_at DESC);
CREATE INDEX IF NOT EXISTS idx_orders_number ON orders.orders (order_number);
CREATE INDEX IF NOT EXISTS idx_orders_coupon_id ON orders.orders (order_coupon_id);
CREATE INDEX IF NOT EXISTS idx_orders_user_uuid ON orders.orders (order_user_uuid);

CREATE INDEX IF NOT EXISTS idx_order_items_order ON orders.order_items (order_item_order_id);
CREATE INDEX IF NOT EXISTS idx_order_items_order_uuid ON orders.order_items (order_item_order_uuid);
CREATE INDEX IF NOT EXISTS idx_order_items_product_id ON orders.order_items (order_item_product_id);
CREATE INDEX IF NOT EXISTS idx_order_items_product_uuid ON orders.order_items (order_item_product_uuid);

CREATE INDEX IF NOT EXISTS idx_tracking_order ON orders.order_tracking_events (event_order_id, event_created_at DESC);

CREATE INDEX IF NOT EXISTS idx_order_returns_user_id ON orders.order_returns (return_user_id);
CREATE INDEX IF NOT EXISTS idx_returns_order ON orders.order_returns (return_order_id);
CREATE INDEX IF NOT EXISTS idx_returns_user ON orders.order_returns (return_user_id, return_created_at DESC);
CREATE INDEX IF NOT EXISTS idx_returns_status ON orders.order_returns (return_status);
CREATE INDEX IF NOT EXISTS idx_returns_shipping_code ON orders.order_returns (return_shipping_code);
CREATE UNIQUE INDEX IF NOT EXISTS idx_returns_active_per_order ON orders.order_returns (return_order_id) WHERE (return_status = ANY (ARRAY[1, 2]));

CREATE INDEX IF NOT EXISTS idx_order_sagas_active ON orders.order_sagas (updated_at) WHERE (state IN ('STARTED', 'COMPENSATING'));

CREATE INDEX IF NOT EXISTS idx_outbox_events_pending ON orders.outbox_events (status, created_at) WHERE (status = 'PENDING');
CREATE INDEX IF NOT EXISTS idx_we_unprocessed ON orders.webhook_events (we_processed, we_received_at) WHERE (we_processed = false);

-- Triggers
DROP TRIGGER IF EXISTS set_order_updated_at ON orders.orders;
CREATE TRIGGER set_order_updated_at
    BEFORE UPDATE ON orders.orders
    FOR EACH ROW EXECUTE FUNCTION update_order_updated_at();

DROP TRIGGER IF EXISTS set_return_updated_at ON orders.order_returns;
CREATE TRIGGER set_return_updated_at
    BEFORE UPDATE ON orders.order_returns
    FOR EACH ROW EXECUTE FUNCTION update_return_updated_at();

-- Public compatibility views
CREATE OR REPLACE VIEW public.orders AS SELECT * FROM orders.orders;
CREATE OR REPLACE VIEW public.order_items AS SELECT * FROM orders.order_items;
CREATE OR REPLACE VIEW public.order_tracking_events AS SELECT * FROM orders.order_tracking_events;
CREATE OR REPLACE VIEW public.order_returns AS SELECT * FROM orders.order_returns;
CREATE OR REPLACE VIEW public.order_sagas AS SELECT * FROM orders.order_sagas;
CREATE OR REPLACE VIEW public.outbox_events AS SELECT * FROM orders.outbox_events;
CREATE OR REPLACE VIEW public.webhook_events AS SELECT * FROM orders.webhook_events;

-- Grants
DO $$
BEGIN
    IF EXISTS (SELECT FROM pg_roles WHERE rolname = 'order_svc') THEN
        GRANT USAGE ON SCHEMA orders TO order_svc;
        GRANT ALL ON ALL TABLES IN SCHEMA orders TO order_svc;
        GRANT ALL ON ALL SEQUENCES IN SCHEMA orders TO order_svc;
    END IF;
END $$;
