-- Order Domain Dedicated Schema Migration

CREATE SCHEMA IF NOT EXISTS orders;

SET search_path TO orders, public;

CREATE TABLE IF NOT EXISTS orders (
    order_id            INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_uuid          UUID DEFAULT gen_random_uuid() NOT NULL UNIQUE,
    order_number        VARCHAR(50) NOT NULL UNIQUE,
    order_user_id       INT NOT NULL,
    order_user_uuid     UUID NOT NULL,
    order_customer_name VARCHAR(100) NOT NULL,
    order_customer_email VARCHAR(255) NOT NULL,
    order_shipping_name VARCHAR(100) NOT NULL,
    order_shipping_phone VARCHAR(20) NOT NULL,
    order_shipping_address TEXT NOT NULL,
    order_total_amount  NUMERIC(12,2) NOT NULL CHECK (order_total_amount >= 0),
    order_refunded_amount NUMERIC(12,2) DEFAULT 0.00 NOT NULL CHECK (order_refunded_amount >= 0),
    order_payment_method SMALLINT NOT NULL CHECK (order_payment_method IN (1, 2)),
    order_payment_status SMALLINT DEFAULT 1 NOT NULL CHECK (order_payment_status IN (1, 2, 3, 4)),
    order_note          TEXT,
    order_status        SMALLINT DEFAULT 1 NOT NULL CHECK (order_status IN (1, 2, 3, 4, 5, 6, 7)),
    order_cancelled_at  TIMESTAMPTZ,
    order_created_at    TIMESTAMPTZ DEFAULT now() NOT NULL,
    order_updated_at    TIMESTAMPTZ DEFAULT now() NOT NULL,
    order_coupon_id     INT,
    order_coupon_code   VARCHAR(50),
    order_subtotal_amount NUMERIC(12,2) DEFAULT 0.00 NOT NULL,
    order_discount_amount NUMERIC(12,2) DEFAULT 0.00 NOT NULL,
    order_shipping_provider VARCHAR(50),
    order_shipping_code VARCHAR(100),
    order_shipping_fee  NUMERIC(12,2) DEFAULT 0.00 NOT NULL,
    order_expected_delivery TIMESTAMPTZ,
    order_delivered_at  TIMESTAMPTZ,
    order_returned_at   TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS order_items (
    order_item_id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_item_uuid       UUID DEFAULT gen_random_uuid() NOT NULL UNIQUE,
    order_item_order_id   INT NOT NULL REFERENCES orders(order_id) ON DELETE CASCADE,
    order_item_product_id INT NOT NULL,
    order_item_price      NUMERIC(12,2) NOT NULL CHECK (order_item_price >= 0),
    order_item_quantity   INT NOT NULL CHECK (order_item_quantity > 0),
    order_item_subtotal   NUMERIC(12,2) NOT NULL CHECK (order_item_subtotal >= 0),
    product_uuid          UUID NOT NULL,
    product_name          VARCHAR(255) NOT NULL,
    product_image_url     TEXT,
    product_slug          VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS order_tracking_events (
    event_id        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_order_id  INT NOT NULL REFERENCES orders(order_id) ON DELETE CASCADE,
    event_status    SMALLINT NOT NULL,
    event_message   TEXT NOT NULL,
    event_location  VARCHAR(255),
    event_created_at TIMESTAMPTZ DEFAULT now() NOT NULL
);

CREATE TABLE IF NOT EXISTS order_returns (
    return_id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    return_uuid       UUID DEFAULT gen_random_uuid() NOT NULL UNIQUE,
    return_order_id   INT NOT NULL REFERENCES orders(order_id) ON DELETE CASCADE,
    return_user_id    INT NOT NULL,
    return_reason     VARCHAR(255) NOT NULL,
    return_status     SMALLINT DEFAULT 1 NOT NULL CHECK (return_status IN (1, 2, 3, 4, 5)),
    return_admin_note TEXT,
    return_created_at TIMESTAMPTZ DEFAULT now() NOT NULL,
    return_updated_at TIMESTAMPTZ DEFAULT now() NOT NULL,
    return_items      JSONB DEFAULT '[]'::jsonb NOT NULL,
    return_refund_amount NUMERIC(12,2) DEFAULT 0.00 NOT NULL
);

CREATE TABLE IF NOT EXISTS order_sagas (
    order_uuid       UUID PRIMARY KEY,
    user_uuid        UUID NOT NULL,
    idempotency_key  VARCHAR(100) NOT NULL,
    state            VARCHAR(20) NOT NULL DEFAULT 'STARTED',
    last_step        VARCHAR(30),
    payload          JSONB NOT NULL,
    snapshot         JSONB,
    failure_reason   TEXT,
    attempts         INT NOT NULL DEFAULT 0,
    next_retry_at    TIMESTAMPTZ,
    created_at       TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at       TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT chk_saga_state CHECK (state IN ('STARTED', 'COMPENSATING', 'CONFIRMED', 'FAILED')),
    CONSTRAINT uq_saga_idem   UNIQUE (user_uuid, idempotency_key)
);

CREATE INDEX IF NOT EXISTS idx_order_sagas_active
    ON order_sagas (updated_at)
    WHERE state IN ('STARTED', 'COMPENSATING');

CREATE INDEX IF NOT EXISTS idx_orders_user_id ON orders(order_user_id);
CREATE INDEX IF NOT EXISTS idx_orders_status ON orders(order_status);
CREATE INDEX IF NOT EXISTS idx_orders_uuid ON orders(order_uuid);
CREATE INDEX IF NOT EXISTS idx_order_items_order_id ON order_items(order_item_order_id);
CREATE INDEX IF NOT EXISTS idx_order_items_product_uuid ON order_items(product_uuid);
