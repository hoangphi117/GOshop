-- Migration for standalone shopping_inventory database

CREATE TABLE IF NOT EXISTS inventory_stocks (
    inventory_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id         INT,
    product_uuid       UUID NOT NULL UNIQUE,
    product_name       VARCHAR(255) NOT NULL DEFAULT '',
    product_sku        VARCHAR(100) NOT NULL DEFAULT '',
    product_image_url  VARCHAR(500) NOT NULL DEFAULT '',
    quantity           INT NOT NULL DEFAULT 0 CHECK (quantity >= 0),
    reserved_quantity  INT NOT NULL DEFAULT 0 CHECK (reserved_quantity >= 0),
    created_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at         TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_inventory_stocks_product_id ON inventory_stocks(product_id);
CREATE INDEX IF NOT EXISTS idx_inventory_stocks_product_uuid ON inventory_stocks(product_uuid);

CREATE TABLE IF NOT EXISTS stock_movements (
    movement_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    movement_uuid     UUID DEFAULT gen_random_uuid() NOT NULL UNIQUE,
    product_id        INT,
    product_uuid      UUID NOT NULL,
    change_type       VARCHAR(50) NOT NULL,
    quantity_change   INT NOT NULL,
    stock_before      INT NOT NULL,
    stock_after       INT NOT NULL,
    reference_id      VARCHAR(100),
    reference_type    VARCHAR(50),
    actor_id          INT,
    actor_uuid        UUID,
    actor_name        VARCHAR(100),
    note              TEXT,
    created_at        TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_stock_movements_product_uuid ON stock_movements(product_uuid, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_stock_movements_product_id ON stock_movements(product_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_stock_movements_type ON stock_movements(change_type, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_stock_movements_reference ON stock_movements(reference_type, reference_id);
CREATE INDEX IF NOT EXISTS idx_stock_movements_created ON stock_movements(created_at DESC);

-- Unique idempotency indexes
CREATE UNIQUE INDEX IF NOT EXISTS uq_stock_movements_idempotency_uuid 
    ON stock_movements (reference_type, reference_id, product_uuid) 
    WHERE reference_id IS NOT NULL AND reference_type IS NOT NULL;

CREATE UNIQUE INDEX IF NOT EXISTS uq_stock_movements_idempotency_id 
    ON stock_movements (reference_type, reference_id, product_id) 
    WHERE reference_id IS NOT NULL AND reference_type IS NOT NULL AND product_id IS NOT NULL;
