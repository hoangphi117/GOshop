-- Categories
CREATE TABLE IF NOT EXISTS categories (
    category_id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_uuid        UUID DEFAULT gen_random_uuid() NOT NULL UNIQUE,
    category_name        VARCHAR(100) NOT NULL,
    category_slug        VARCHAR(100) NOT NULL UNIQUE,
    category_description TEXT,
    category_status      INT DEFAULT 1 CHECK (category_status IN (1, 2)) NOT NULL,
    category_deleted_at  TIMESTAMPTZ DEFAULT NULL,
    category_created_at  TIMESTAMPTZ DEFAULT now() NOT NULL,
    category_updated_at  TIMESTAMPTZ DEFAULT now() NOT NULL
);

-- Products
CREATE TABLE IF NOT EXISTS products (
    product_id           INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_uuid         UUID DEFAULT gen_random_uuid() NOT NULL UNIQUE,
    product_name         VARCHAR(200) NOT NULL,
    product_slug         VARCHAR(200) NOT NULL UNIQUE,
    product_description  TEXT,
    product_price        NUMERIC(12,2) NOT NULL CHECK (product_price > 0),
    product_stock        INT DEFAULT 0 CHECK (product_stock >= 0),
    product_sku          VARCHAR(50) UNIQUE,
    product_category_id  INT NOT NULL REFERENCES categories(category_id),
    product_image_url    TEXT,
    product_status       INT DEFAULT 1 CHECK (product_status IN (1, 2, 3)) NOT NULL,
    product_deleted_at   TIMESTAMPTZ DEFAULT NULL,
    product_created_at   TIMESTAMPTZ DEFAULT now() NOT NULL,
    product_updated_at   TIMESTAMPTZ DEFAULT now() NOT NULL
);

-- Categories
CREATE INDEX idx_categories_list ON categories(category_deleted_at, category_created_at DESC);
CREATE INDEX idx_categories_slug ON categories(category_slug);

-- Products
CREATE INDEX idx_products_list ON products(product_deleted_at, product_category_id, product_status, product_created_at DESC);
CREATE INDEX idx_products_slug ON products(product_slug);

-- Trigger Categories
CREATE OR REPLACE FUNCTION update_category_updated_at()
RETURNS TRIGGER AS $$
BEGIN
	NEW.category_updated_at = now();
	RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER set_category_updated_at
BEFORE UPDATE on categories
FOR EACH ROW
EXECUTE FUNCTION update_category_updated_at();

-- Trigger Products
CREATE OR REPLACE FUNCTION update_product_updated_at()
RETURNS TRIGGER AS $$
BEGIN
	NEW.product_updated_at = now();
	RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER set_product_updated_at
BEFORE UPDATE on products
FOR EACH ROW
EXECUTE FUNCTION update_product_updated_at();