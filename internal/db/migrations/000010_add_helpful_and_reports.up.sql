ALTER TABLE product_reviews
    ADD COLUMN IF NOT EXISTS review_helpful_count INT DEFAULT 0 NOT NULL;

CREATE TABLE IF NOT EXISTS product_review_helpful_votes (
    vote_id     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    review_id   INT NOT NULL REFERENCES product_reviews(review_id) ON DELETE CASCADE,
    user_id     INT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    created_at  TIMESTAMPTZ DEFAULT now() NOT NULL,
    CONSTRAINT uq_review_helpful_user UNIQUE(review_id, user_id)
);

CREATE TABLE IF NOT EXISTS product_review_reports (
    report_id    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    review_id    INT NOT NULL REFERENCES product_reviews(review_id) ON DELETE CASCADE,
    user_id      INT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    reason       VARCHAR(50) NOT NULL, -- spam, inappropriate, fake, other
    details      TEXT,
    created_at   TIMESTAMPTZ DEFAULT now() NOT NULL,
    CONSTRAINT uq_review_report_user UNIQUE(review_id, user_id)
);

CREATE INDEX IF NOT EXISTS idx_review_reports_review ON product_review_reports(review_id);

CREATE INDEX IF NOT EXISTS idx_review_helpful_votes_review ON product_review_helpful_votes(review_id);