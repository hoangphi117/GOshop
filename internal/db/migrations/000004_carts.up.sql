CREATE TABLE IF NOT EXISTS carts (
    cart_id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cart_uuid       UUID DEFAULT gen_random_uuid() NOT NULL UNIQUE,
    cart_user_id    INT NOT NULL UNIQUE REFERENCES users(user_id) ON DELETE CASCADE,
    cart_created_at TIMESTAMPTZ DEFAULT now() NOT NULL,
    cart_updated_at TIMESTAMPTZ DEFAULT now() NOT NULL
);

CREATE TABLE IF NOT EXISTS cart_items (
    cart_item_id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cart_item_uuid       UUID DEFAULT gen_random_uuid() NOT NULL UNIQUE,
    cart_item_cart_id    INT NOT NULL REFERENCES carts(cart_id) ON DELETE CASCADE,
    cart_item_product_id INT NOT NULL REFERENCES products(product_id) ON DELETE CASCADE,
    cart_item_quantity   INT NOT NULL CHECK (cart_item_quantity > 0),
    cart_item_created_at TIMESTAMPTZ DEFAULT now() NOT NULL,
    cart_item_updated_at TIMESTAMPTZ DEFAULT now() NOT NULL,
    CONSTRAINT uk_cart_product UNIQUE (cart_item_cart_id, cart_item_product_id)
);

-- Do not create a separate CREATE INDEX idx_carts_user: cart_user_id already has UNIQUE,
-- PostgreSQL automatically creates a unique index implicitly — creating another one is redundant and wasteful.
CREATE INDEX idx_cart_items_cart ON cart_items(cart_item_cart_id);

CREATE OR REPLACE FUNCTION update_cart_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.cart_updated_at = now();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER set_cart_updated_at
BEFORE UPDATE ON carts
FOR EACH ROW EXECUTE FUNCTION update_cart_updated_at();

CREATE OR REPLACE FUNCTION update_cart_item_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.cart_item_updated_at = now();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER set_cart_item_updated_at
BEFORE UPDATE ON cart_items
FOR EACH ROW EXECUTE FUNCTION update_cart_item_updated_at();

CREATE OR REPLACE FUNCTION touch_cart_on_item_change()
RETURNS TRIGGER AS $$
BEGIN
    UPDATE carts SET cart_updated_at = now()
    WHERE cart_id = COALESCE(NEW.cart_item_cart_id, OLD.cart_item_cart_id);
    RETURN COALESCE(NEW, OLD);
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER touch_cart_after_item_change
AFTER INSERT OR UPDATE OR DELETE ON cart_items
FOR EACH ROW EXECUTE FUNCTION touch_cart_on_item_change();