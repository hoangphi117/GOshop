// Rebuild the local @font-face sheet: download the variable woff2 subsets for
// Rubik and Nunito Sans once and reference them from public/fonts.
//
// next/font/google fetches Google's CSS at build time; that fetch returns
// font URLs without a .woff2 extension on some runners, which crashes the
// loader. Vendoring removes the build-time network dependency entirely.
//
// Run from frontend/apps/storefront:  node scripts/vendor-fonts.mjs
import { mkdir, writeFile, readFile, unlink } from "node:fs/promises";
import path from "node:path";

const UA =
  "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 " +
  "(KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36";

const FONTS = [
  {
    family: "Rubik",
    cssVar: "--font-rubik",
    url: "https://fonts.googleapis.com/css2?family=Rubik:wght@300..900&display=swap",
  },
  {
    family: "Nunito Sans",
    cssVar: "--font-nunito-sans",
    url: "https://fonts.googleapis.com/css2?family=Nunito+Sans:wght@300..800&display=swap",
  },
];

const outDir = path.join(process.cwd(), "src", "fonts");
const cssPath = path.join(process.cwd(), "src", "app", "fonts.css");

await mkdir(outDir, { recursive: true });

const blocks = [];

for (const font of FONTS) {
  const slug = font.family.toLowerCase().replace(/\s+/g, "-");
  const res = await fetch(font.url, { headers: { "user-agent": UA } });
  if (!res.ok) throw new Error(`${font.family}: CSS ${res.status}`);
  const css = await res.text();

  // Each @font-face is preceded by a /* subset */ comment.
  const faces = [...css.matchAll(/\/\* ([^*]+) \*\/\s*@font-face \{([\s\S]*?)\}/g)];
  if (!faces.length) throw new Error(`${font.family}: no @font-face blocks`);

  for (const [, subset, body] of faces) {
    const src = /url\((https:[^)]+)\)/.exec(body)?.[1];
    const range = /unicode-range: ([^;]+);/.exec(body)?.[1];
    const weight = /font-weight: ([^;]+);/.exec(body)?.[1];
    if (!src || !range || !weight) throw new Error(`${font.family}/${subset}: incomplete @font-face`);

    const name = `${slug}-${subset.trim()}.woff2`;
    const file = await fetch(src, { headers: { "user-agent": UA } });
    if (!file.ok) throw new Error(`${font.family}/${subset}: font ${file.status}`);
    await writeFile(path.join(outDir, name), Buffer.from(await file.arrayBuffer()));

    blocks.push(
      `@font-face {\n` +
        `  font-family: "${font.family}";\n` +
        `  font-style: normal;\n` +
        `  font-weight: ${weight};\n` +
        `  font-display: swap;\n` +
        `  src: url("../fonts/${name}") format("woff2");\n` +
        `  unicode-range: ${range};\n` +
        `}`,
    );
  }
  console.log(`${font.family}: ${faces.length} subsets`);
}

const header =
  "/* Self-hosted Google Fonts (Rubik, Nunito Sans).\n" +
  " * Generated by scripts/vendor-fonts.mjs — do not edit by hand.\n" +
  " * Vendored so `next build` never depends on fonts.googleapis.com. */\n\n";

await writeFile(cssPath, header + blocks.join("\n\n") + "\n", "utf8");
console.log(`wrote ${cssPath}`);
